# ---------------------------------------------------------------- 解析工具

def parse_courses(blob: str) -> List[Tuple[str, int, float]]:
    """把 "课程名:学期:学分,课程名:学期:学分" 解析成元组列表。"""
    out: List[Tuple[str, int, float]] = []
    for chunk in (blob or "").split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        parts = chunk.rsplit(":", 2)
        if len(parts) != 3:
            raise ValueError(f"课程字段格式错误：{chunk!r}")
        name, term, credits = parts
        out.append((name.strip(), int(term), float(credits)))
    return out


def major_by_name(name: str) -> Dict[str, Any]:
    for major in MAJORS:
        if major["name"] == name:
            return major
    raise KeyError(name)


def curriculum_for(major_name: str) -> List[Tuple[str, int, float, str]]:
    """返回该专业完整课程表：[(课程名, 学期, 学分, 课程类型), ...]，按学期排序。

    课程类型：通识必修 / 学科基础 / 专业核心。
    """
    major = major_by_name(major_name)
    rows: List[Tuple[str, int, float, str]] = []

    # 公共课里属于「专业基础」的几门单独归为学科基础，其余算通识必修
    stem_names = {"高等数学（上）", "高等数学（下）", "线性代数", "概率论与数理统计",
                  "大学物理", "高等数学（经管类）", "高等数学（经管类）下"}
    for name, term, credits in parse_courses(PUBLIC_COURSES[major["category"]]):
        kind = "学科基础" if name in stem_names else "通识必修"
        rows.append((name, term, credits, kind))
    for name, term, credits in parse_courses(major["core_courses"]):
        rows.append((name, term, credits, "专业核心"))

    rows.sort(key=lambda item: (item[1], item[0]))
    return rows


def all_curriculum_rows() -> List[Tuple[str, List[Tuple[str, int, float, str]]]]:
    return [(major["name"], curriculum_for(major["name"])) for major in MAJORS]


