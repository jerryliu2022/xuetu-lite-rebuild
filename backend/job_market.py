def _pick_course_video(
    con: sqlite3.Connection,
    major: str,
    skill: str,
    courses: List[Dict[str, Any]],
) -> Optional[str]:
    """把一个技能落到本专业培养方案里最贴的那门课，再取该课热度最高的一条资源。"""
    keywords = SKILL_KEYWORDS.get(skill) or [skill]
    best_course: Optional[Dict[str, Any]] = None
    best_score = 0
    for course in courses:
        name = course["name"]
        score = 0
        for keyword in keywords:
            if keyword == name:
                score = max(score, 1000 + len(keyword))
            elif keyword in name:
                score = max(score, 600 + len(keyword))
            elif name in keyword:
                score = max(score, 400 + len(name))
        if score > best_score:
            best_score = score
            best_course = course
    if best_course is None:
        return None
    found = con.execute(
        "SELECT video_id FROM video WHERE course_id=? ORDER BY popularity DESC LIMIT 1",
        (best_course["course_id"],),
    ).fetchone()
    return found["video_id"] if found else None


def build_job_market(con: sqlite3.Connection) -> Dict[str, Any]:
    """重建 job / skill_course_map 两张表，返回统计与未映射技能清单。"""
    majors = {
        row["name"]: row
        for row in con.execute("SELECT * FROM major").fetchall()
        if isinstance(row["name"], str)
    }
    courses_by_major: Dict[str, List[Dict[str, Any]]] = {}
    for name in majors:
        courses_by_major[name] = [
            dict(row)
            for row in con.execute(
                "SELECT course_id, name, semester, course_kind FROM course WHERE major=? ORDER BY semester",
                (name,),
            ).fetchall()
        ]

    con.execute("DELETE FROM job")
    con.execute("DELETE FROM skill_course_map")

    inserted = 0
    unmapped: Dict[str, List[str]] = {}
    thin: List[Dict[str, Any]] = []
    mapped_pairs: set = set()

    for major, spec_list in JOBS_BY_MAJOR.items():
        if major not in majors:
            continue
        cluster = CLUSTER_OF.get(major, "")
        peers = [m for m in CLUSTERS.get(cluster, []) if m != major][:2]
        required = "，".join([major] + peers)
        for index, spec in enumerate(spec_list, start=1):
            title, company, city, salary, fresh, skills, requirement = spec
            job_id = f"J{majors[major]['major_id'][-2:]}{index:02d}"
            skill_list = [s.strip() for s in skills.split(",") if s.strip()]
            con.execute(
                """
                INSERT OR REPLACE INTO job
                  (job_id,title,company,city,salary,fresh,major_match,required_major,
                   skills,requirement,source,source_url,major,published_at,
                   source_raw_id,source_collected_at)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,NULL)
                """,
                (
                    job_id, title, company, city, salary, fresh, "高度匹配", required,
                    "，".join(skill_list), requirement,
                    "BOSS直聘" if index % 2 else "拉勾网",
                    "https://www.zhipin.com/" if index % 2 else "https://www.lagou.com/",
                    major, _published_at(major, index),
                    None,
                ),
            )
            inserted += 1
            job_skills: List[str] = []
            for skill in skill_list:
                video_id = _pick_course_video(con, major, skill, courses_by_major[major])
                if not video_id:
                    unmapped.setdefault(skill, []).append(major)
                    continue
                job_skills.append(skill)
                if (skill, video_id) in mapped_pairs:
                    continue
                mapped_pairs.add((skill, video_id))
                con.execute(
                    "INSERT OR REPLACE INTO skill_course_map (skill, video_id, prerequisite_skill) VALUES (?,?,?)",
                    (skill, video_id, SKILL_PREREQ.get(skill, "")),
                )
            # 一个岗位能落到课程上的技能少于 2 个，说明这条岗位的路径撑不起来，记下来补数据
            if len(job_skills) < 2:
                thin.append({"job_id": job_id, "major": major, "title": title, "mapped": job_skills})
    con.commit()
    return {
        "jobs": inserted,
        "skill_course_rows": len(mapped_pairs),
        "skills": len({s for s, _ in mapped_pairs}),
        "majors_covered": len(JOBS_BY_MAJOR),
        "thin_jobs": thin,
        "unmapped_skills": unmapped,
    }


def _published_at(major: str, index: int) -> str:
    """给岗位一个稳定的近两年发布时间，避免每次重建都变。"""
    seed = sum(ord(ch) for ch in major) + index * 37
    month = 1 + seed % 12
    day = 1 + (seed * 7) % 27
    return f"2026-{month:02d}-{day:02d}"


def match_level(student_major: str, job_major: str) -> str:
    """岗位与学生的匹配档位：同专业 -> 高度匹配，同簇 -> 一般匹配，跨簇 -> 相关延伸。"""
    if not job_major or job_major == student_major:
        return "高度匹配"
    if CLUSTER_OF.get(job_major) and CLUSTER_OF.get(job_major) == CLUSTER_OF.get(student_major):
        return "一般匹配"
    return "相关延伸"


def path_skills_for(skills: List[str]) -> List[str]:
    """把岗位技能展开成含先修节点的有序技能集合（粗略版，细排序由 recommender 做）。"""
    needed: List[str] = []
    for skill in skills:
        for part in [p.strip() for p in SKILL_PREREQ.get(skill, "").split(",") if p.strip()]:
            if part not in needed:
                needed.append(part)
        if skill not in needed:
            needed.append(skill)
    return needed


